// Writes api/_lib/bots.ts: bot id -> creator key, so the score API can check
// which bots a run published without bundling the whole bot list.
// `npm run sync-bots` runs this after it refreshes src/bots.json.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const bots = JSON.parse(await readFile(join(root, 'src/bots.json'), 'utf8'));
const map = Object.fromEntries(bots.filter((b) => b.u).map((b) => [b.u, b.h || b.cn || '']));
await writeFile(
  join(root, 'api/_lib/bots.ts'),
  `// Generated by scripts/api-bots.mjs from src/bots.json. Do not edit.\n// Bot id -> creator key (X handle, or display name when there is no handle).\nexport const BOT_CREATOR: Record<string, string> = ${JSON.stringify(map)};\n`,
);
console.log(`wrote api/_lib/bots.ts (${Object.keys(map).length} bots)`);
