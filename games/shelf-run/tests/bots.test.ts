// The bot data and the cards built from it: real bots, dupes and scams.
import { existsSync, readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import raw from '../src/bots.json';
import {
  BOT_COUNT,
  CATS,
  CREATOR_COUNT,
  FAKE_OFFICIAL,
  FAKE_PEOPLE,
  PLAY_CATS,
  byline,
  catColor,
  dupeOf,
  fakeAvatar,
  realBot,
  resetPools,
  scamBot,
  tagline,
  viralBots,
} from '../src/bots';
import { BOT_CREATOR } from '../api/_lib/bots';

interface RawBot {
  n: string;
  e: string;
  d: string;
  c: string;
  h: string;
  cn: string;
  u: string;
  a: string;
  l: number;
}
const BOTS = raw as RawBot[];
const keyOf = (b: { n: string; h: string }) => `${b.n}|${b.h}`;

describe('src/bots.json', () => {
  it('has bots, and every one is complete', () => {
    expect(BOTS.length).toBeGreaterThan(100);
    for (const b of BOTS) {
      expect(b.n.trim(), b.u).not.toBe('');
      expect(b.u, b.n).toMatch(/^[\w-]+(\/[\w-]+)*$/);
      expect(typeof b.l).toBe('number');
      expect(b.h).not.toMatch(/^@/);
    }
  });

  it('has unique bot ids', () => {
    expect(new Set(BOTS.map((b) => b.u)).size).toBe(BOTS.length);
  });

  it('uses only known categories', () => {
    const known = new Set(CATS.map((c) => c.name));
    expect(BOTS.filter((b) => !known.has(b.c)).map((b) => b.c)).toEqual([]);
    for (const c of PLAY_CATS) expect(known.has(c)).toBe(true);
  });

  it('has an avatar file in public/avatars for every bot that names one', () => {
    const missing = BOTS.filter((b) => b.a && !existsSync(new URL(`../public/avatars/${b.a}`, import.meta.url))).map((b) => b.a);
    expect(missing).toEqual([]);
  });

  it('matches api/_lib/bots.ts (run `node scripts/api-bots.mjs` if not)', () => {
    const want = Object.fromEntries(BOTS.filter((b) => b.u).map((b) => [b.u, b.h || b.cn || '']));
    expect(BOT_CREATOR).toEqual(want);
    expect(readFileSync(new URL('../api/_lib/bots.ts', import.meta.url), 'utf8')).toMatch(/^\/\/ Generated by scripts\/api-bots\.mjs/);
  });

  it('counts bots and creators for the start screen', () => {
    expect(BOT_COUNT).toBe(BOTS.length);
    expect(CREATOR_COUNT).toBeGreaterThan(10);
    expect(CREATOR_COUNT).toBeLessThanOrEqual(BOT_COUNT);
  });
});

describe('tagline', () => {
  it('keeps a short first sentence whole, without the period', () => {
    expect(tagline('Plans your week. Also does more.')).toBe('Plans your week');
  });

  it('does not stop at abbreviations', () => {
    expect(tagline('Compares gas cars vs. EVs for you. More text.')).toBe('Compares gas cars vs. EVs for you');
  });

  it('turns em dashes into commas', () => {
    expect(tagline('Fast — and free.')).toBe('Fast, and free');
  });

  it('cuts long text at a natural break and adds an ellipsis', () => {
    const t = tagline('Turns your messy notes into a tidy plan for the week, with reminders that actually show up on time.');
    expect(t).toBe('Turns your messy notes into a tidy plan for the week…');
  });

  it('fits every real description on a card', () => {
    for (const b of BOTS) {
      const t = tagline(b.d);
      expect(t.length, b.d).toBeLessThanOrEqual(65);
      expect(t).not.toContain('—');
    }
  });
});

describe('real bots', () => {
  it('never repeats a bot within a run until the category runs out', () => {
    resetPools();
    const seen = new Set<string>();
    const n = BOTS.filter((b) => b.c === 'Money').length;
    const keys = Array.from({ length: n }, () => realBot('Money', seen).key);
    expect(new Set(keys).size).toBe(n);
  });

  it('keeps handing out bots after a category runs out', () => {
    resetPools();
    const seen = new Set<string>();
    const n = BOTS.filter((b) => b.c === 'Home').length;
    for (let i = 0; i < n + 5; i++) expect(realBot('Home', seen).cat).toBe('Home');
  });

  it('never picks a bot that is on a shelf right now', () => {
    resetPools();
    const home = BOTS.filter((b) => b.c === 'Home');
    const onShelf = new Set(home.slice(0, home.length - 1).map(keyOf));
    const seen = new Set(home.map(keyOf)); // everything seen, so the pool refills
    for (let i = 0; i < 10; i++) expect(onShelf.has(realBot('Home', seen, onShelf).key)).toBe(false);
  });

  it('falls back to any bot for an unknown category', () => {
    resetPools();
    expect(realBot('Nope', new Set()).kind).toBe('real');
  });

  it('builds cards that link to the real bot', () => {
    resetPools();
    const s = realBot('Productivity', new Set());
    expect(s.url).toMatch(/^https:\/\/x\.ai\/bot\/[\w-]+$/);
    expect(s.link.startsWith('x.ai/bot/')).toBe(true);
    expect(s.kind).toBe('real');
  });

  it('gives every real bot an id the score API knows, even ids with slashes', () => {
    resetPools();
    const seen = new Set<string>();
    for (const c of CATS) {
      const n = BOTS.filter((b) => b.c === c.name).length;
      for (let i = 0; i < n; i++) {
        const s = realBot(c.name, seen);
        expect(s.id && s.id in BOT_CREATOR, s.name).toBe(true);
        expect(s.url).toBe(`https://x.ai/bot/${s.id}`);
      }
    }
    expect(seen.size).toBe(new Set(BOTS.map(keyOf)).size);
  });

  it('marks popular bots as viral', () => {
    const v = viralBots();
    expect(v.length).toBeGreaterThan(0);
    for (const b of v) expect(b.viral && b.likes >= 10).toBe(true);
  });

  it('makes a dupe that points back at the original', () => {
    resetPools();
    const b = realBot('Money', new Set());
    const d = dupeOf(b);
    expect(d).toMatchObject({ kind: 'dupe', dupeOf: b.key, name: b.name });
    expect(d.uid).not.toBe(b.uid);
  });
});

describe('scams', () => {
  const realHandles = new Set(BOTS.map((b) => b.h.toLowerCase()).filter(Boolean));
  const realNames = new Set(BOTS.map((b) => b.n.toLowerCase()));

  it('never use a real creator handle', () => {
    for (const f of [...FAKE_OFFICIAL, ...FAKE_PEOPLE]) expect(realHandles.has(f.handle.toLowerCase()), f.handle).toBe(false);
  });

  for (const tier of [0, 1, 2] as const) {
    it(`tier ${tier} carries one tell and no real creator`, () => {
      for (let i = 0; i < 200; i++) {
        const s = scamBot(tier, ['Money'], new Set());
        expect(s.kind).toBe('scam');
        expect(s.url).toBeNull();
        expect(realHandles.has(s.handle.toLowerCase())).toBe(false);
        expect(s.stamp && s.missLine && s.tell).toBeTruthy();
        if (tier === 2) expect(s.link.startsWith('x.ai/bot/')).toBe(true);
        else expect(s.link.startsWith('x.ai/bot/')).toBe(false);
        if (tier !== 1) expect(realNames.has(s.name.toLowerCase()), s.name).toBe(false);
      }
    });
  }

  it('tier 1 copies a real bot but never one that names its creator', () => {
    for (let i = 0; i < 200; i++) {
      const s = scamBot(1, ['Productivity'], new Set());
      const copied = BOTS.find((b) => b.n === s.name);
      if (!copied) continue; // fell back to a loud scam
      if (copied.h) expect(s.name.toLowerCase()).not.toContain(copied.h.toLowerCase());
      expect(s.name).not.toMatch(/\bby\b/);
    }
  });

  it('tier 1 falls back to a loud scam when nothing is left to copy', () => {
    const everything = new Set(BOTS.map(keyOf));
    expect(scamBot(1, ['Money'], everything).tier).toBe(0);
  });

  it('draws a stable avatar for a fake account', () => {
    expect(fakeAvatar('Someone')).toBe(fakeAvatar('someone'));
    expect(fakeAvatar('a')).toMatch(/^data:image\/svg\+xml,/);
  });
});

describe('helpers', () => {
  it('bylines prefer the handle, then the name, then the site', () => {
    expect(byline({ handle: 'nick', creator: 'Nick' })).toBe('@nick');
    expect(byline({ handle: '', creator: 'Nick' })).toBe('Nick');
    expect(byline({ handle: '', creator: '' })).toBe('grokbotshelf.com');
  });

  it('colors categories, with a grey fallback', () => {
    expect(catColor('Money')).toBe('#3fae6a');
    expect(catColor('Nope')).toBe('#8b98a5');
  });
});
